// Writes supabase/schema-snapshot.sql: the live Axiom tables, columns, types,
// defaults, primary and foreign keys, read from the database's REST schema.
// The live database is the source of truth; this snapshot is what the
// migration tests (src/lib/tenancy/*.test.ts) build their copy from.
//
//   node --env-file=.env.local scripts/schema-snapshot.mjs
//
// Needs NEXT_PUBLIC_AXIOM_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY. Read-only.
// (Check constraints, indexes, RLS, functions and triggers aren't in the REST
// schema, so they aren't in the snapshot.)

import { writeFileSync } from "node:fs";

const url = process.env.NEXT_PUBLIC_AXIOM_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) throw new Error("Set NEXT_PUBLIC_AXIOM_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY");

const res = await fetch(`${url}/rest/v1/`, { headers: { apikey: key, Authorization: `Bearer ${key}` } });
if (!res.ok) throw new Error(`Schema fetch failed: ${res.status}`);
const defs = (await res.json()).definitions;

const quote = (v) => `'${String(v).replace(/'/g, "''")}'`;
function defaultSql(p) {
  if (p.default === undefined) return "";
  const v = p.default;
  if (typeof v === "number" || typeof v === "boolean") return ` default ${v}`;
  if (typeof v === "object") return ` default ${quote(JSON.stringify(v))}::${p.format}`;
  // Function calls and casts come through as SQL; plain values as text.
  if (/\(.*\)$|::|^CURRENT_(DATE|TIMESTAMP)$/.test(v)) return ` default ${v}`;
  return ` default ${quote(v)}`;
}

const tables = [];
const fks = [];
for (const [table, def] of Object.entries(defs).sort(([a], [b]) => a.localeCompare(b))) {
  const required = new Set(def.required || []);
  const cols = [];
  const pk = [];
  for (const [col, p] of Object.entries(def.properties)) {
    const desc = p.description || "";
    if (desc.includes("<pk/>")) pk.push(col);
    const fk = desc.match(/<fk table='([^']+)' column='([^']+)'\/>/);
    if (fk) fks.push(`alter table public.${table} add foreign key (${col}) references public.${fk[1]} (${fk[2]});`);
    cols.push(`  ${col} ${p.format}${defaultSql(p)}${required.has(col) && !desc.includes("<pk/>") ? " not null" : ""}`);
  }
  if (pk.length) cols.push(`  primary key (${pk.join(", ")})`);
  tables.push(`create table public.${table} (\n${cols.join(",\n")}\n);`);
}

const out = `-- Live Axiom schema snapshot (tables, columns, keys). Generated by
-- scripts/schema-snapshot.mjs on ${new Date().toISOString().slice(0, 10)}; do not edit by hand.

${tables.join("\n\n")}

${fks.join("\n")}
`;
writeFileSync(new URL("../supabase/schema-snapshot.sql", import.meta.url), out);
console.log(`Wrote ${Object.keys(defs).length} tables, ${fks.length} foreign keys.`);
